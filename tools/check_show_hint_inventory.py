#!/usr/bin/env python3
import argparse
import pprint
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / 'src/cubrid_language/show_hint_inventory.py'
RULES = ('show_type', 'show_type_of_like', 'show_type_of_where', 'show_type_arg1',
         'show_type_arg1_opt', 'show_type_arg_named', 'show_heap_type_id',
         'show_type_id', 'show_type_id_dot_id', 'of_index_indexes_keys')


def extract(source):
    table = source.split('PT_HINT parser_hint_table[] = {', 1)[1].split('};', 1)[0]
    hints = sorted(re.findall(r'INIT_PT_HINT\("([A-Z_]+)",\s*(PT_HINT_[A-Z_]+)\)', table))
    block = re.search(r'(?ms)^show_stmt\s*\n(.*?)^\s*;', source).group(1)
    block = re.sub(r'\{\{.*?\}\}', '', block, flags=re.S)
    first = set()
    for alt in re.split(r'(?m)^\s*[:|]', block):
        words = alt.split()
        if words and words[0] == 'SHOW':
            if words[1] == 'opt_full':
                first.update(('FULL', words[2]))
            elif words[1].isupper():
                first.add(words[1])
            elif words[1] not in RULES:
                raise ValueError('unhandled SHOW rule ' + words[1])
    for name in RULES:
        rule = re.search(r'(?ms)^' + name + r'\s*\n(.*?)^\s*;', source).group(1)
        rule = re.sub(r'\{\{.*?\}\}', '', rule, flags=re.S)
        for alt in re.split(r'(?m)^\s*[:|]', rule):
            words = alt.split()
            if words:
                if not words[0].isupper():
                    raise ValueError('unhandled first symbol in ' + name + ': ' + words[0])
                first.add(words[0])
    productions = []
    for name in ('show_stmt', *RULES, 'opt_full', 'of_from_in', 'opt_for_current_user'):
        rule = re.search(r'(?ms)^' + name + r'\s*\n(.*?)^\s*;', source).group(1)
        rule = re.sub(r'\{\{.*?\}\}', '', rule, flags=re.S)
        rule = re.sub(r'/\*.*?\*/', '', rule, flags=re.S)
        alternatives = tuple(' '.join(alt.split()) for alt in re.split(r'(?m)^\s*[:|]', rule)[1:])
        productions.append((name, alternatives))
    return {'source_commit': 'cc947788d3b7dc402f46192d0f3299ddcc8563ba',
            'profile': 'cubrid-11.5.0.2704-cc94778', 'hints': tuple(hints),
            'show_first': tuple(sorted(first)), 'show_productions': tuple(productions)}


def fixture(source):
    names = ('show_stmt', *RULES, 'opt_full', 'of_from_in', 'opt_for_current_user')
    rules = []
    for name in names:
        rule = re.search(r'(?ms)^' + name + r'\s*\n(.*?)^\s*;', source).group(0)
        rules.append(re.sub(r'\{\{.*?\}\}', '', rule, flags=re.S))
    table = source.split('PT_HINT parser_hint_table[] = {', 1)[1].split('};', 1)[0]
    content = '\n\n'.join(rules) + '\n\nPT_HINT parser_hint_table[] = {' + table + '};\n'
    return '\n'.join(line.rstrip() for line in content.splitlines()) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('grammar', type=Path)
    parser.add_argument('--inventory', type=Path, default=INVENTORY)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--write-fixture', type=Path)
    args = parser.parse_args()
    source = args.grammar.read_text()
    result = extract(source)
    if args.write_fixture:
        args.write_fixture.write_text(fixture(source))
    rendered = '# Generated by tools/check_show_hint_inventory.py.\n' + ''.join(
        key.upper() + ' = ' + pprint.pformat(value, width=100) + '\n' for key, value in result.items())
    if args.write:
        args.inventory.write_text(rendered)
    elif rendered != args.inventory.read_text():
        print('inventory differs from grammar', file=sys.stderr)
        return 1
    else:
        print(f"inventory matches {len(result['hints'])} hints and {len(result['show_first'])} SHOW first words")
    return 0


if __name__ == '__main__':
    sys.exit(main())
